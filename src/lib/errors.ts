export function mapError(e: unknown): string {
  const m = e instanceof Error ? e.message : String(e);
  for (const [re, ar] of MAP) if (re.test(m)) return ar;
  console.error("[unmapped error]", m);
  return "حدث خطأ غير متوقع. حاول مرة أخرى.";
}
